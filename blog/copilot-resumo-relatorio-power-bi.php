    <h2>Perguntas frequentes</h2>
    <div class="blog-faq-grid">
      <div class="faq-item">
        <h3>O resumo do Copilot considera os filtros aplicados na tela?</h3>
        <p>Sim, ele parte do estado atual da página, incluindo segmentações e filtros já selecionados.</p>
      </div>
      <div class="faq-item">
        <h3>O Copilot pode errar na interpretação dos dados?</h3>
        <p>Pode descrever corretamente o que os visuais mostram e ainda assim faltar contexto de negócio — vale sempre revisar antes de repassar o resumo como conclusão.</p>
      </div>
      <div class="faq-item">
        <h3>Dá para pedir resumo de mais de uma página ao mesmo tempo?</h3>
        <p>O fluxo padrão é por página; para uma visão de todo o relatório, o ideal é pedir um resumo por página e comparar.</p>
      </div>
      <div class="faq-item">
        <h3>Isso substitui montar uma análise escrita?</h3>
        <p>Serve como ponto de partida rápido, não como substituto de uma análise mais aprofundada quando o cenário exige.</p>
      </div>

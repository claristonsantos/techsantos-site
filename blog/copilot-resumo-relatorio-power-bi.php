    <h1>Copilot no Power BI: resuma um relatório inteiro em linguagem natural</h1>

    <p>Antes de uma reunião de resultado, ler visual por visual de um relatório pra montar um resumo mental do que mudou consome um tempo que ninguém tem sobrando. O Copilot do Power BI oferece um atalho: pedir um resumo em texto corrido do que os visuais da página estão mostrando, incluindo tendências e pontos fora do padrão.</p>

    <div class="key-takeaways">
      <span class="kt-label">Resumo rápido</span>
      <ul>
        <li>O Copilot lê os visuais de uma página do relatório e gera um resumo em linguagem natural do que eles mostram.</li>
        <li>O resumo pode destacar tendências, variações e valores fora do padrão, sem você precisar abrir cada gráfico individualmente.</li>
        <li>Serve como ponto de partida para uma reunião de resultado, não como substituto da análise — vale conferir os números originais antes de repassar o resumo adiante.</li>
        <li>Funciona dentro do relatório já publicado, sobre os dados que estão filtrados na tela no momento do pedido.</li>
      </ul>
    </div>

    <h2>Como pedir um resumo ao Copilot</h2>
    <p>Dentro do relatório, abra o painel do Copilot e peça algo como "resuma esta página" ou "quais são os principais destaques deste relatório". O Copilot examina os visuais visíveis na página — considerando os filtros e segmentações aplicados no momento — e devolve um texto corrido explicando o que os números mostram.</p>

    <video controls preload="metadata" playsinline>

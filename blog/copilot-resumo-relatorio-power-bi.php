    <h2>O que o resumo consegue (e não consegue) captar</h2>
    <p>O Copilot é bom em descrever o que está na tela: qual categoria teve maior crescimento, onde um valor está fora do padrão em relação ao resto. O que ele não sabe é o contexto de negócio por trás do número — se uma queda de vendas em março é sazonal ou é um problema real, isso ainda depende de quem conhece a operação. Trate o resumo como o primeiro parágrafo de uma análise, não como a conclusão final.</p>

    <h2>Onde esse resumo ajuda mais no dia a dia</h2>
    <p>É mais útil em relatórios que várias pessoas revisam com frequência — um resumo automático agiliza quem só precisa da visão geral antes de decidir se vale a pena investigar mais fundo um visual específico, sem abrir mão de quem quer aprofundar continuar tendo acesso aos dados completos.</p>

